// Writes content/media.ts: the size, dimensions and blur preview of every image and video in
// public/, so the default content can reference media by path (the same shape as media from
// Storyblok) and scripts can read it without a bundler.
//
//   npm run media
//
// Run it after adding or replacing a file in public/images, public/videos or public/works.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";
import sharp from "sharp";

const roots = ["images", "videos", "works"];
const imageTypes = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".svg"]);
const videoTypes = new Set([".mp4", ".webm"]);
const darkBlur =
  "data:image/svg+xml;charset=utf-8,%3Csvg%20xmlns%3D'http%3A%2F%2Fwww.w3.org%2F2000%2Fsvg'%20viewBox%3D'0%200%2010%2010'%3E%3Crect%20width%3D'10'%20height%3D'10'%20fill%3D'%23161616'%2F%3E%3C%2Fsvg%3E";

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

const entries: Record<string, { width: number; height: number; bytes: number; blurDataURL?: string }> = {};

for (const root of roots) {
  for (const file of files(join("public", root)).sort()) {
    const type = extname(file).toLowerCase();
    const path = `/${file.slice("public/".length)}`;
    const bytes = statSync(file).size;
    if (videoTypes.has(type)) {
      entries[path] = { width: 0, height: 0, bytes };
    } else if (imageTypes.has(type)) {
      const { width = 0, height = 0 } = await sharp(file).metadata();
      // A tiny JPEG stands in while the image loads; vector art gets a flat dark tile
      const blurDataURL =
        type === ".svg"
          ? darkBlur
          : `data:image/jpeg;base64,${(await sharp(file).resize(16).jpeg({ quality: 50 }).toBuffer()).toString("base64")}`;
      entries[path] = { width, height, bytes, blurDataURL };
    }
  }
}

writeFileSync(
  "content/media.ts",
  `// Generated by scripts/media-manifest.ts (npm run media). Don't edit by hand.\n\nexport const mediaManifest: Record<string, { width: number; height: number; bytes: number; blurDataURL?: string }> = ${JSON.stringify(entries, null, 2)};\n`
);
console.log(`content/media.ts: ${Object.keys(entries).length} files`);
